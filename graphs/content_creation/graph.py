def prepare_input(query: str, caller: Optional[str] = None, **kwargs) -> Dict[str, Any]:
    """Translates incoming text query / kwargs into initial generic ContentCreationState."""
    if caller and "<caller>" not in query:
        formatted_query = f"<caller>{caller}</caller>\n{query}"
    else:
        formatted_query = query

    project_dir = kwargs.get("project_dir")
    if not project_dir:
        m_pdir = re.search(r'project_dir[:=]\s*["\']?([^"\'\s,]+)["\']?', query, re.IGNORECASE)
        if m_pdir:
            project_dir = m_pdir.group(1)
        else:
            project_dir = "pkm/wiki/software/ayla-first-words"

    topic = kwargs.get("topic") or kwargs.get("word")
    if not topic:
        m_topic = re.search(r'(?:topic|word)[:=]\s*["\']?([a-zA-Z0-9_ -]+)["\']?', query, re.IGNORECASE)
        if m_topic:
            topic = m_topic.group(1).strip()
        else:
            clean_q = query.replace("<caller>", "").replace("</caller>", "").strip()
            if clean_q and len(clean_q.split()) == 1:
                topic = clean_q
            elif "dog" in clean_q.lower():
                topic = "dog"
            elif "cat" in clean_q.lower():
                topic = "cat"
            else:
                topic = clean_q if clean_q else "scene"

    manifest_path = kwargs.get("manifest_path") or f"{project_dir}/01_Project_Manifest.md"
    creator_instructions_path = kwargs.get("creator_instructions_path") or f"{project_dir}/02_Creator_Instructions.md"
    qc_playbook_path = kwargs.get("qc_playbook_path") or f"{project_dir}/03_QC_Playbook.md"

    output_dir = kwargs.get("output_dir") or f"{project_dir}/assets/{topic}"
    image_path = kwargs.get("image_path") or f"{output_dir}/{topic}_image.jpg"
    video_plot_path = kwargs.get("video_plot_path") or f"{output_dir}/{topic}_video_plot.md"
    video_path = kwargs.get("video_path") or f"{output_dir}/{topic}_video.mp4"
    copy_path = kwargs.get("copy_path") or f"{output_dir}/{topic}_copy.md"
    qc_timestamps = kwargs.get("qc_timestamps") or [1.0, 2.5, 4.0]

    session_id = kwargs.get("session_id", f"session_{topic}")

    return {
        "project_dir": project_dir,
        "topic": topic,
        "manifest_path": manifest_path,
        "creator_instructions_path": creator_instructions_path,
        "qc_playbook_path": qc_playbook_path,
        "output_dir": output_dir,
        "image_path": image_path,
        "video_plot_path": video_plot_path,
        "video_path": video_path,
        "copy_path": copy_path,
        "image_prompt": "",
        "video_plot_content": "",
        "video_plot_qc_passed": False,
        "video_plot_feedback": "",
        "extracted_frames": [],
        "qc_timestamps": qc_timestamps,
        "video_qc_passed": False,
        "video_qc_feedback": "",
        "copy_text": "",
        "final_package": {},
        "video_plot_attempts": 0,
        "messages": [HumanMessage(content=formatted_query)],
        "query": formatted_query,
        "session_id": session_id,
        "error_message": ""
    }

def format_output(state: Dict[str, Any]) -> str:
    """Extracts final reply text from ContentCreationState."""
    if isinstance(state, dict):
        if "messages" in state and state["messages"]:
            last_msg = state["messages"][-1]
            if isinstance(last_msg, AIMessage):
                return last_msg.content
            elif isinstance(last_msg, dict) and last_msg.get("role") == "assistant":
                return last_msg.get("content", "")
        if state.get("final_package") and "copy_text" in state["final_package"]:
            return state["final_package"]["copy_text"]
        if state.get("copy_text"):
            return state["copy_text"]
        if state.get("video_plot_qc_passed") and state.get("image_path"):
            topic = state.get("topic", "scene")
            image_path = state.get("image_path", "")
            video_plot_path = state.get("video_plot_path", "")
            return (
                f"🛑 **[HITL GATE 1: Image & Video Plot Approval Required]**\n\n"
                f"- **Topic**: `{topic}`\n"
                f"- **Base Image**: `{image_path}`\n"
                f"- **Video Plot Doc**: `{video_plot_path}`\n\n"
                f"Base image and video plot have passed QC and are ready for approval before generating video."
            )
        if state.get("error_message"):
            return f"Content creation failed: {state['error_message']}"
        if "messages" in state and state["messages"]:
            last_msg = state["messages"][-1]
            if hasattr(last_msg, "content"):
                return last_msg.content
            elif isinstance(last_msg, dict) and "content" in last_msg:
                return last_msg["content"]
            return str(last_msg)
    return str(state)
