class ContentCreationState(TypedDict, total=False):
    # --- Project Context ---
    project_dir: str                  # e.g., "pkm/wiki/software/ayla-first-words"
    topic: str                        # e.g., "dog"

    # --- Instruction Documents ---
    manifest_path: str                # e.g., "{project_dir}/01_Project_Manifest.md"
    creator_instructions_path: str    # e.g., "{project_dir}/02_Creator_Instructions.md"
    qc_playbook_path: str             # e.g., "{project_dir}/03_QC_Playbook.md"

    # --- Asset Paths ---
    output_dir: str                   # e.g., "{project_dir}/assets/{topic}"
    image_path: str                   # e.g., "{output_dir}/{topic}_image.jpg"
    video_plot_path: str              # e.g., "{output_dir}/{topic}_video_plot.md"
    video_path: str                   # e.g., "{output_dir}/{topic}_video.mp4"
    copy_path: str                    # e.g., "{output_dir}/{topic}_copy.md"

    # --- Internal Graph State & QC ---
    image_prompt: str
    video_plot_content: str
    video_plot_qc_passed: bool
    video_plot_feedback: str

    extracted_frames: List[str]       # Generated by extract_video_frames
    qc_timestamps: List[float]        # Configurable list of timestamps, default [1.0, 2.5, 4.0]
    video_qc_passed: bool
    video_qc_feedback: str

    copy_text: str
    final_package: Dict[str, Any]

    # --- Auxiliary / Runtime State ---
    video_plot_attempts: int
    max_video_plot_reviews: int
    video_qc_attempts: int
    max_video_reviews: int
    messages: Annotated[Sequence[BaseMessage], operator.add]
    query: str
    session_id: str
    error_message: str

def _extract_motion_prompt_from_plot(plot_content: str, state: Dict[str, Any]) -> str:
    """Extracts the motion prompt blockquote under **Prompt:** or Motion Prompt header from the Video Plot Markdown."""
    topic = state.get("topic", "scene")
    if plot_content:
        lines = plot_content.split("\n")
        in_prompt = False
        prompt_lines = []
        for line in lines:
            if "Motion Prompt" in line or "**Prompt:**" in line:
                in_prompt = True
                if "**Prompt:**" in line:
                    parts = line.split("**Prompt:**", 1)
                    if len(parts) > 1 and parts[1].strip():
                        prompt_lines.append(parts[1].strip().lstrip(">").strip())
                continue
            if in_prompt:
                if line.startswith("---") or line.startswith("## ") or line.startswith("# "):
                    break
                if line.strip().startswith(">"):
                    prompt_lines.append(line.strip().lstrip(">").strip())
                elif prompt_lines and not line.strip():
                    break
                elif prompt_lines:
                    prompt_lines.append(line.strip())
        if prompt_lines:
            extracted = " ".join(prompt_lines).strip()
            if extracted:
                return extracted

    return f"Cinematic video scene for topic: {topic}. High quality, smooth camera movement, focused subject animation."

